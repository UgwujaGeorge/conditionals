// Writes src/lib/abi.ts from the Foundry build: run `forge build` at the repo root first.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../../out/${name}.sol/${name}.json`, import.meta.url))).abi;
const conditionals = read("ConditionalsV2");
const zap = read("ConditionalsZap");
const facts = read("ConditionalsFacts");
const erc20 = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
];
writeFileSync(
  new URL("../src/lib/abi.ts", import.meta.url),
  `// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit.\n\nexport const conditionalsAbi = ${JSON.stringify(conditionals, null, 2)} as const;\n\nexport const zapAbi = ${JSON.stringify(zap, null, 2)} as const;\n\nexport const factsAbi = ${JSON.stringify(facts, null, 2)} as const;\n\nexport const erc20Abi = ${JSON.stringify(erc20, null, 2)} as const;\n`,
);
console.log("wrote src/lib/abi.ts");
